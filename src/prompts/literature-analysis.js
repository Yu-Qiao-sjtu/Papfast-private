/**
 * 根据论文信息生成分析提示
 */
export function generateAnalysisPrompt(paper) {
  const journalInfo = paper.journalInfoText || paper.journal || '未知期刊';

  return `请分析以下论文：

**标题**: ${paper.title}
${paper.titleZh ? `**中文标题**: ${paper.titleZh}` : ''}

**期刊**: ${journalInfo}

**摘要 (英文)**:
${paper.abstract || '无摘要'}

${paper.abstractZh ? `**摘要 (中文翻译)**:\n${paper.abstractZh}` : ''}

${paper.keywords?.length ? `**关键词**: ${paper.keywords.slice(0, 5).join(', ')}` : ''}

${paper.pmid ? `**PMID**: ${paper.pmid}` : ''}
${paper.doi ? `**DOI**: ${paper.doi}` : ''}

---
请按照 7 个模块进行分析，重点关注因果强度预判和逻辑断点预警。

**重要提醒**：不要使用 LaTeX 数学符号（如 $\\\\uparrow$, $\\\\rightarrow$, $\\\\downarrow$），请使用 Unicode 箭头符号（↑ ↓ → ↔）或中文描述代替。`;
}
